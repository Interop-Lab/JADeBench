function isValidStatusCode(code) {
  return (
    (code >= 1000 && code <= 1014 && code !== 1004 && code !== 1005 && code !== 1006) ||
    (code >= 3000 && code <= 4999)
  );
}

function _isValidUTF8(buf) {
  const len = buf.length;
  let i = 0;

  while (i < len) {
    if ((buf[i] & 0x80) === 0) {
      i++;
    } else if ((buf[i] & 0xe0) === 0xc0) {
      if (i + 1 >= len || (buf[i + 1] & 0xc0) !== 0x80) return false;
      i += 2;
    } else if ((buf[i] & 0xf0) === 0xe0) {
      if (i + 2 >= len || (buf[i + 1] & 0xc0) !== 0x80 || (buf[i + 2] & 0xc0) !== 0x80) return false;
      i += 3;
    } else if ((buf[i] & 0xf8) === 0xf0) {
      if (i + 3 >= len || (buf[i + 1] & 0xc0) !== 0x80 || (buf[i + 2] & 0xc0) !== 0x80 || (buf[i + 3] & 0xc0) !== 0x80) return false;
      i += 4;
    } else {
      return false;
    }
  }

  return true;
}

function isBlob(object) {
  return object instanceof Blob ||
    (typeof Blob !== 'undefined' && object && typeof object === 'object' && typeof object.arrayBuffer === 'function' && typeof object.type === 'string' && typeof object.stream === 'function' && typeof object.constructor === 'function' && typeof object.constructor.name === 'string' && /^(Blob|File)$/.test(object.constructor.name) && /^(Blob|File)$/.test(object[Symbol.toStringTag]));
}

