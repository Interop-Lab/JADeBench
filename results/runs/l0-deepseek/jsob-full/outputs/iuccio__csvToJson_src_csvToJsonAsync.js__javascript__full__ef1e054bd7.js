const require_errors = __commonJS((module, exports) => {
  'use strict';

  class CsvError extends Error {
    constructor(message, code, details = {}) {
      super(message);
      this.name = 'CsvError';
      this.code = code;
      this.details = details;
      Error.captureStackTrace(this, this.constructor);
    }

    toString() {
      let result = this.name + ': ' + this.message;
      if (this.details && Object.keys(this.details).length > 0) {
        result += '\nDetails:';
        Object.entries(this.details).forEach(([key, value]) => {
          result += `\n  ${key}: ${this._formatValue(value)}`;
        });
      }
      return result;
    }

    _formatValue(value) {
      if (value === null) return 'null';
      if (value === undefined) return 'undefined';
      if (typeof value === 'string') return `"${value}"`;
      if (typeof value === 'object') return JSON.stringify(value);
      return String(value);
    }
  }

  class FileOperationError extends CsvError {
    constructor(operation, path, error, extra = '') {
      const message = `File operation failed: '${operation}' on '${path}': ${error}${extra ? '\n' + extra : ''}`;
      super(message, 'FILE_OPERATION_ERROR', {
        operation,
        path,
        error
      });
      this.name = 'FileOperationError';
    }
  }

  class ConfigurationError extends CsvError {
    constructor(message, details = {}) {
      super(message, 'CONFIGURATION_ERROR', details);
      this.name = 'ConfigurationError';
    }

    static conflictingOptions(optionName, value) {
      return new ConfigurationError(
        `Conflicting configuration options: '${optionName}' cannot be used with '${value}'.`,
        { optionName, value, conflictingOption: 'conflictingOption' }
      );
    }

    static invalidOptionType(value) {
      return new ConfigurationError(
        `Invalid configuration option type: expected string or number, received ${typeof value} (${value}).`,
        { parameterName: 'value', value, type: typeof value }
      );
    }
  }

  class CsvFormatError extends CsvError {
    constructor(message, details = {}) {
      super(message, 'CSV_FORMAT_ERROR', details);
      this.name = 'CsvFormatError';
    }

    static malformedCsv() {
      return new CsvFormatError('Malformed CSV: unclosed quoted field detected.');
    }

    static invalidDelimiter(delimiter = 'delimiter') {
      return new CsvFormatError(`Invalid delimiter: '${delimiter}' must be a single character.`, {
        location: delimiter
      });
    }
  }

  class JsonValidationError extends CsvError {
    constructor(operation, path, error) {
      const message = `JSON validation failed for '${operation}' on '${path}': ${error.message}`;
      super(message, 'JSON_VALIDATION_ERROR', {
        operation,
        path,
        error: error.message
      });
      this.name = 'JsonValidationError';
      this.originalError = error;
    }
  }

  class InputValidationError extends CsvError {
    constructor(message, details = {}) {
      super(message, 'INPUT_VALIDATION_ERROR', details);
      this.name = 'InputValidationError';
    }

    static invalidInputType(value) {
      return new InputValidationError(
        `Invalid input type: expected string, Buffer, or Readable stream, received ${typeof value} (${value}).`,
        { parameterName: 'value', value, type: typeof value }
      );
    }

    static invalidStream(stream) {
      return new InputValidationError(
        `Invalid stream: expected a readable stream, received ${typeof stream} (${stream}).`,
        { parameterName: 'stream', value: stream, type: typeof stream }
      );
    }
  }

  class StreamProcessingError extends CsvError {
    constructor(message, details = {}) {
      super(message, 'STREAM_PROCESSING_ERROR', details);
      this.name = 'StreamProcessingError';
    }

    static invalidStreamSource() {
      return new StreamProcessingError('Invalid stream source: expected a readable stream.');
    }

    static streamError(originalError) {
      return new StreamProcessingError(
        `Stream processing failed: ${originalError.message}`,
        { originalError: originalError.message }
      );
    }
  }

  exports.CsvError = CsvError;
  exports.FileOperationError = FileOperationError;
  exports.ConfigurationError = ConfigurationError;
  exports.CsvFormatError = CsvFormatError;
  exports.JsonValidationError = JsonValidationError;
  exports.InputValidationError = InputValidationError;
  exports.StreamProcessingError = StreamProcessingError;
});

const require_fileUtils = __commonJS((module, exports) => {
  'use strict';

  const fs = require('fs');
  const { FileOperationError } = require_errors();

  const DEFAULT_ENCODING = 'utf8';
  const SUPPORTED_ENCODINGS = new Set(['utf8', 'utf-8']);

  class FileUtils {
    isSupportedEncoding(encoding) {
      return SUPPORTED_ENCODINGS.has(encoding);
    }

    readFile(filePath, encoding) {
      if (this.isSupportedEncoding(encoding)) {
        return fs.readFileSync(filePath, encoding);
      }
      return fs.readFileSync(filePath);
    }

    readFileAsString(filePath) {
      return typeof filePath === 'string' ? filePath : filePath.toString();
    }

    readFileWithErrorHandling(filePath, encoding) {
      return new FileOperationError('readFile', filePath, encoding);
    }

    readFileSync(filePath, encoding) {
      if (this.isSupportedEncoding(encoding)) {
        const content = fs.readFileSync(filePath, 'utf8');
        return this.decodeBuffer(content, encoding);
      }
      return this.readFileAsString(fs.readFileSync(filePath, encoding));
    }

    readFileAsync(filePath, encoding = 'utf8') {
      try {
        return this.readFileSync(filePath, encoding);
      } catch (error) {
        throw this.createFileOperationError(filePath, error);
      }
    }

    readFileLines(filePath, encoding) {
      if (this.isSupportedEncoding(encoding)) {
        return fs.readFileSync(filePath, 'utf8')
          .split(/\r?\n/)
          .map(line => this.decodeBuffer(line, encoding));
      }
      return fs.readFileSync(filePath, encoding)
        .toString()
        .split(/\r?\n/)
        .map(line => this.decodeBuffer(line));
    }

    readFileLinesWithErrorHandling(filePath, encoding = 'utf8') {
      if (fs.promises && typeof fs.promises.readFile === 'function') {
        return this.readFileLines(filePath, encoding)
          .catch(error => {
            throw this.createFileOperationError(filePath, error);
          });
      }

      return new Promise((resolve, reject) => {
        fs.readFile(filePath, encoding, (error, data) => {
          if (error) {
            reject(this.createFileOperationError(filePath, error));
            return;
          }
          try {
            const content = this.isSupportedEncoding(encoding)
              ? this.decodeBuffer(this.readFileAsString(data), encoding)
              : this.readFileAsString(data);
            resolve(content);
          } catch (error) {
            reject(this.createFileOperationError(filePath, error));
          }
        });
      });
    }

    writeFile(filePath, content) {
      fs.writeFileSync(filePath, content, 'utf8');
    }

    writeFileWithErrorHandling(filePath, content) {
      try {
        this.writeFile(filePath, content);
      } catch (error) {
        throw this.createFileOperationError(filePath, error);
      }
    }

    appendFile(filePath, content) {
      fs.appendFileSync(filePath, content, 'utf8');
    }

    appendFileWithErrorHandling(filePath, content) {
      try {
        this.appendFile(filePath, content);
      } catch (error) {
        throw this.createFileOperationError(filePath, error);
      }
    }

    createFileOperationError(filePath, error) {
      return new FileOperationError('file operation', filePath, error);
    }

    decodeBuffer(buffer, encoding) {
      if (this.isSupportedEncoding(encoding)) {
        return Buffer.from(buffer, encoding).toString('utf8');
      }
      return buffer;
    }

    writeFileAsync(filePath, content) {
      return new Promise((resolve, reject) => {
        fs.writeFile(filePath, content, 'utf8', error => {
          if (error) {
            reject(this.createFileOperationError(filePath, error));
            return;
          }
          resolve();
        });
      });
    }

    appendFileAsync(filePath, content) {
      return new Promise((resolve, reject) => {
        fs.appendFile(filePath, content, 'utf8', error => {
          if (error) {
            reject(this.createFileOperationError(filePath, error));
            return;
          }
          resolve();
        });
      });
    }
  }

  exports.FileUtils = new FileUtils();
});

const require_stringUtils = __commonJS((module, exports) => {
  'use strict';

  const PATTERNS = {
    INTEGER: /^-?\d+$/,
    FLOAT: /^-?\d*\.\d+$/,
    WHITESPACE: /\s/g
  };

  const DEFAULTS = {
    DELIMITER: ',',
    QUOTE: '"'
  };

  class StringUtils {
    static patterns = PATTERNS;
    static defaults = DEFAULTS;

    normalizeString(value, trimWhitespace) {
      if (!trimWhitespace) return '';
      return trimWhitespace
        ? value.replace(StringUtils.patterns.WHITESPACE, '')
        : value.trim();
    }

    parseValue(value) {
      if (this.isInteger(value)) return this.parseInteger(value);
      if (this.isFloat(value)) return this.parseFloat(value);
      if (this.isBoolean(value)) return this.parseBoolean(value);
      if (this.isNull(value)) return null;
      return String(value);
    }

    isNonEmptyArray(value = []) {
      return Array.isArray(value) && value.every(item => Boolean(item));
    }

    isNull(value) {
      return value === undefined || value === null || value === '';
    }

    isInteger(value) {
      const trimmed = value.trim();
      return StringUtils.patterns.INTEGER.test(trimmed);
    }

    isFloat(value) {
      return StringUtils.patterns.FLOAT.test(value);
    }

    isBoolean(value) {
      return value === 'true' || value === 'false';
    }

    parseBoolean(value) {
      return value === 'true';
    }

    parseInteger(value) {
      return parseInt(value, 10);
    }

    parseFloat(value) {
      return parseFloat(value);
    }

    parseNumber(value) {
      const number = Number(value);
      return Number.isFinite(number) ? number : String(value);
    }

    parseNumeric(value) {
      const number = Number(value);
      return Number.isFinite(number) ? number : String(value);
    }
  }

  exports.StringUtils = new StringUtils();
});

