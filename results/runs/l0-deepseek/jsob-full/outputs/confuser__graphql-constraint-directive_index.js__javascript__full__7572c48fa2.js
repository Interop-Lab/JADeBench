const require_string = __commonJS((exports, module) => {
  const { GraphQLScalarType } = require("graphql");
  const { contains, isLength } = require("validator");
  const formats = require_formats();
  const ConstraintDirectiveError = require_error();

  class ConstraintStringType extends GraphQLScalarType {
    constructor(fieldName, typeName, baseType, config, options = {}) {
      super({
        name: typeName,
        serialize(value) {
          value = baseType.serialize(value);
          validate(fieldName, config, value, options);
          return value;
        },
        parseValue(value) {
          value = baseType.parseValue(value);
          validate(fieldName, config, value, options);
          return baseType.parseValue(value);
        },
        parseLiteral(ast) {
          const value = baseType.parseLiteral(ast);
          validate(fieldName, config, value, options);
          return value;
        },
      });
    }
  }

  function getConfigValue(config, defaultValue) {
    return config?.value ?? defaultValue;
  }

  function validate(fieldName, config, value, options = {}) {
    if (config.minLength && !isLength(value, { min: config.minLength })) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "minLength")} must be at least ${config.minLength} characters long`,
        [{ arg: "minLength", value: config.minLength }]
      );
    }
    if (config.maxLength && !isLength(value, { max: config.maxLength })) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "maxLength")} must be at most ${config.maxLength} characters long`,
        [{ arg: "maxLength", value: config.maxLength }]
      );
    }
    if (config.startsWith && !value.startsWith(config.startsWith)) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "startsWith")} must start with ${config.startsWith}`,
        [{ arg: "startsWith", value: config.startsWith }]
      );
    }
    if (config.endsWith && !value.endsWith(config.endsWith)) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "endsWith")} must end with ${config.endsWith}`,
        [{ arg: "endsWith", value: config.endsWith }]
      );
    }
    if (config.includes && !value.includes(config.includes)) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "includes")} must include ${config.includes}`,
        [{ arg: "includes", value: config.includes }]
      );
    }
    if (config.notIncludes && contains(value, config.notIncludes)) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "notIncludes")} must not include ${config.notIncludes}`,
        [{ arg: "notIncludes", value: config.notIncludes }]
      );
    }
    if (config.regex && !new RegExp(config.regex).test(value)) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "regex")} must match regex ${config.regex}`,
        [{ arg: "regex", value: config.regex }]
      );
    }
    if (config.format) {
      const customFormats = options.customFormats || {};
      const availableFormats = { ...formats, ...(customFormats.formats || {}) };
      const validator = availableFormats[config.format];
      if (!validator) {
        throw new ConstraintDirectiveError(
          fieldName,
          `${getConfigValue(config, "format")} has no validator for format ${config.format}`,
          [{ arg: "format", value: config.format }]
        );
      }
      try {
        validator(value, config);
      } catch (error) {
        throw new ConstraintDirectiveError(
          fieldName,
          `${getConfigValue(config, "format")} ${error.message}`,
          [{ arg: "format", value: config.format }]
        );
      }
    }
  }

  module.exports = {
    ConstraintStringType,
    validate,
  };
});

const require_number = __commonJS((exports, module) => {
  const { GraphQLScalarType } = require("graphql");
  const ConstraintDirectiveError = require_error();

  class ConstraintNumberType extends GraphQLScalarType {
    constructor(fieldName, typeName, baseType, config) {
      super({
        name: typeName,
        serialize(value) {
          value = baseType.serialize(value);
          validate(fieldName, config, value);
          return value;
        },
        parseValue(value) {
          value = baseType.parseValue(value);
          validate(fieldName, config, value);
          return baseType.parseValue(value);
        },
        parseLiteral(ast) {
          const value = baseType.parseLiteral(ast);
          validate(fieldName, config, value);
          return value;
        },
      });
    }
  }

  function getPrecision(value) {
    const precision = Number.MAX_SAFE_INTEGER;
    return Math.abs(value) < precision || Math.abs(value) > precision;
  }

  function getConfigValue(config, defaultValue) {
    return config?.value ?? defaultValue;
  }

  function validate(fieldName, config, value) {
    if (config.min !== undefined && value < config.min) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "min")} must be greater than or equal to ${config.min}`,
        [{ arg: "min", value: config.min }]
      );
    }
    if (config.max !== undefined && value > config.max) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "max")} must be less than or equal to ${config.max}`,
        [{ arg: "max", value: config.max }]
      );
    }
    if (config.exclusiveMin !== undefined && value <= config.exclusiveMin) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "exclusiveMin")} must be greater than ${config.exclusiveMin}`,
        [{ arg: "exclusiveMin", value: config.exclusiveMin }]
      );
    }
    if (config.exclusiveMax !== undefined && value >= config.exclusiveMax) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "exclusiveMax")} must be less than ${config.exclusiveMax}`,
        [{ arg: "exclusiveMax", value: config.exclusiveMax }]
      );
    }
    if (config.multipleOf !== undefined && getPrecision(value, config.multipleOf) !== true) {
      throw new ConstraintDirectiveError(
        fieldName,
        `${getConfigValue(config, "multipleOf")} must be a multiple of ${config.multipleOf}`,
        [{ arg: "multipleOf", value: config.multipleOf }]
      );
    }
  }

  module.exports = {
    ConstraintNumberType,
    validate,
  };
});

const require_type_utils = __commonJS((exports, module) => {
  const {
    GraphQLFloat,
    GraphQLInt,
    GraphQLString,
    isNonNullType,
    isScalarType,
    isListType,
    GraphQLID,
  } = require("graphql");
  const { ConstraintStringType, validate: validateString } = require_string();
  const { ConstraintNumberType, validate: validateNumber } = require_number();

  function getConstraintTypeObject(fieldName, baseType, typeName, config) {
    if (baseType === GraphQLString || baseType === GraphQLID) {
      return new ConstraintStringType(fieldName, typeName, baseType, config);
    } else if (baseType === GraphQLFloat || baseType === GraphQLInt) {
      return new ConstraintNumberType(fieldName, typeName, baseType, config);
    } else {
      throw new Error(`Unsupported base type: ${baseType.name}`);
    }
  }

  function getConstraintValidateFn(baseType) {
    if (baseType === GraphQLString || baseType === GraphQLID) {
      return validateString;
    } else if (baseType === GraphQLFloat || baseType === GraphQLInt) {
      return validateNumber;
    } else {
      throw new Error(`Unsupported base type: ${baseType.name}`);
    }
  }

  function getScalarType(type) {
    if (isScalarType(type)) {
      return { type: type };
    } else if (isListType(type)) {
      return { ...getScalarType(type.ofType), list: true };
    } else if (isNonNullType(type) && isScalarType(type.ofType)) {
      return { type: type.ofType, nonNull: true };
    } else if (isNonNullType(type)) {
      return { ...getScalarType(type.ofType), list: true, listNotNull: true };
    } else {
      throw new Error(`Unsupported type: ${type.name}`);
    }
  }

  module.exports = {
    getConstraintTypeObject,
    getConstraintValidateFn,
    getScalarType,
  };
});

